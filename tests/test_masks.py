import pytest
from src.masks import get_mask_card_number, get_mask_account

# Тесты для get_mask_card_number
@pytest.mark.parametrize("card_number, expected", [
    ("1234567890123456", "1234 56** **** 3456"),  # Стандартная длина
    ("123456789012", "Введен некорректный номер карты"),      # Нестандартная длина (12 цифр)
    ("12345678", "Введен некорректный номер карты"),          # Граничный случай (минимальная длина)
    ("", "Номер счета/карты не введен"),                                    # Пустая строка
    ("1234", "Введен некорректный номер карты"),                            # Строка короче 6 символов
    ("12345678901234567890", "Введен некорректный номер карты"),  # Длинный номер (20 цифр)
    ("Visa 1234567890123456", "Visa 1234 56** **** 3456"),  # С нечисловыми символами
])
def test_get_mask_card_number(card_number, expected):
    assert get_mask_card_number(card_number) == expected


# Тесты для get_mask_account
@pytest.mark.parametrize("account, expected", [
    ("12345678901234567890", "**7890"),          # Стандартная длина
    ("12345", "Введен некорректный номер счета"),                         # Короткий номер
    ("", "Номер счета/карты не введен"),                                  # Пустая строка
    ("1", "Введен некорректный номер счета"),                                # Минимальная длина
    ("Счет 12345678", "Введен некорректный номер счета"),            # С нечисловыми символами
])
def test_get_mask_account(account, expected):
    assert get_mask_account(account) == expected